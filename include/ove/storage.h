/**
 * @file storage.h
 * @defgroup ove_storage Storage Types
 * @brief Backend-specific opaque storage types and static-allocation macros.
 *
 * This header selects the correct backend storage header and exposes:
 *
 * - **Opaque storage types** (@c ove_*_storage_t) — raw byte arrays with
 *   the correct size and alignment for each backend's primitive.  Use these
 *   with @c _init() functions for zero-heap (static) allocation.
 *
 * - **@c OVE_*_DEFINE() macros** — file-scope convenience wrappers that
 *   declare a named storage object of the correct type.
 *
 * - **@c OVE_*_DEFINE_STATIC() macros** — one-step primitives that declare
 *   a handle, allocate static storage, and register a C constructor that
 *   initialises the handle before @c main().  Available in both heap and
 *   zero-heap modes — the handle is statically allocated either way.
 *
 * @par Backend selection
 * The correct backend header is chosen at build time via the
 * @c CONFIG_OVE_RTOS_* defines.  Foreign-language toolchains use alternate
 * selection logic:
 *   - `__BINDGEN__` (Rust bindgen): uses exact build-time sizes from
 *     @c storage_sizes.h generated by @c ove_rust.cmake.
 *   - `__ZIG_CIMPORT__` (Zig \@cImport): uses either exact build-time sizes
 *     from @c zig_storage_sizes.h (zero-heap) or minimal 1-byte opaque types
 *     (heap mode).
 *
 * @note In zero-heap mode (@c CONFIG_OVE_ZERO_HEAP) the @c OVE_HEAP_*
 *       gates are not defined, so no heap-backed @c _create()/@c _destroy()
 *       functions are compiled.  Application code must use @c _init() with
 *       caller-supplied storage, or the @c OVE_*_DEFINE_STATIC() macros.
 *       Calling a @c _create() symbol in zero-heap mode is a link error.
 *
 * @par Storage-hygiene contract (Phase 5 audit)
 *
 * Every public @c _init() function accepts a caller-provided
 * @c ove_*_storage_t and **must not** allocate anything itself.  The
 * @c tests/suites/test_init_no_alloc.c regression test enforces this
 * empirically on every backend with @c -Wl,--wrap=malloc engaged
 * (FreeRTOS-QEMU, Zephyr-QEMU, NuttX-QEMU).
 *
 * The @c ove_thread_init() stack-buffer parameter (the final @c void*
 * argument) has per-backend semantics:
 *
 * | Backend  | Uses caller stack? | Notes |
 * |----------|--------------------|-------|
 * | FreeRTOS | ✅                 | `xTaskCreateStatic` consumes it directly. |
 * | Zephyr   | ✅                 | `k_thread_create` over the caller's K_THREAD_STACK_DEFINE buffer. |
 * | NuttX    | ✅ on target ports | `task_create_with_stack()` forwards it to the architecture; NuttX sim may substitute a larger host stack. NuttX still allocates the TCB and task group internally. |
 * | POSIX    | ⚠ Ignored          | Host-mode backend; `pthread_create` manages its own stack. |
 * | WASM     | ⚠ Ignored          | Host-mode backend; host pthreads manage stack. |
 *
 * **For strict zero-heap deployments**: FreeRTOS and Zephyr honor the
 * full storage-hygiene contract. NuttX honors caller stack storage but
 * still allocates its TCB and task group internally; POSIX and WASM are
 * host/sim backends with no zero-heap obligation.
 *
 * @par Storage struct size stability
 *
 * The @c ove_*_storage_t types are concrete (non-opaque) structs whose
 * size is resolvable at C compile time.  This is a deliberate ABI
 * commitment: the Zig binding relies on `@sizeOf(ove_queue_storage_t)`
 * resolving via @c \@cImport at build time, and the Rust binding uses
 * bindgen to derive the same sizes for `MaybeUninit<...>` wrappers.
 * Making them opaque would be a breaking change that requires adding
 * `ove_*_storage_size()` runtime queries and rewriting all binding
 * static-allocation paths.
 *
 * @{
 */

