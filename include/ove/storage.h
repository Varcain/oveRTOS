/* Backend-specific thread stack definition (Zephyr needs K_THREAD_STACK_DEFINE) */
#ifndef OVE_THREAD_STACK_DEFINE_
/**
 * @brief Declare a static thread stack array named @p name with size @p size.
 *
 * @note Always 8-byte aligned (ARM AAPCS); the runtime backstop in
 *       @c ove_thread_init() rejects misaligned stacks with
 *       @c OVE_ERR_INVALID_PARAM, which would silently take down a
 *       caller that hand-rolled a stack at file scope without the
 *       attribute (the C++ NuttX bench used to fail at runtime here:
 *       BSS placement put `<...>_stack` at a 1-byte-aligned offset).
 * @note Overridden by backends that require special alignment (e.g. Zephyr MPU).
 */
#define OVE_THREAD_STACK_DEFINE_(name, size) static uint8_t __attribute__((aligned(8))) name[(size)]
#endif

/* File-static variant of the above — for stacks that need internal linkage
 * (e.g. test framework stacks reused under the same symbol name across
 * multiple TUs).  Includes aligned(8) explicitly since the generic
 * OVE_THREAD_STACK_DEFINE_ doesn't, and AAPCS requires 8-byte alignment
 * for the stack pointer at function-call boundaries.  Zephyr overrides
 * this to pin 'static' onto K_THREAD_STACK_DEFINE since
 * K_THREAD_STACK_DEFINE itself has external linkage. */
#ifndef OVE_THREAD_STACK_DEFINE_STATIC_
#define OVE_THREAD_STACK_DEFINE_STATIC_(name, size) \
	static uint8_t __attribute__((aligned(8))) name[(size)]
#endif

/** @cond INTERNAL */
/* Block-scope static variant — safe inside ({...}) statement expressions. */
#ifndef OVE_THREAD_STACK_BLOCK_STATIC_
#define OVE_THREAD_STACK_BLOCK_STATIC_(name, size) \
	static uint8_t __attribute__((aligned(8))) name[(size)]
#endif
/** @endcond */

/* Class-member variant (no 'static') — for C++ class-embedded stacks.
 * Overridden by backends that need special alignment (e.g. Zephyr MPU). */
#ifndef OVE_THREAD_STACK_MEMBER_
/**
 * @brief Declare a non-static (class-member) thread stack array.
 *
 * Use inside a C++ struct or class body where @c static is not applicable.
 *
 * @note The 8-byte alignment matches `OVE_THREAD_STACK_BLOCK_STATIC_` and
 *       satisfies the ARM AAPCS requirement that the stack pointer be
 *       8-byte aligned at public function boundaries; a misaligned stack
 *       faults immediately on the first thread entry.  The runtime
 *       backstop in @c ove_thread_init() returns @c OVE_ERR_INVALID_PARAM
 *       if a caller bypasses this macro with a hand-rolled array.
 * @note Overridden by backends that require special alignment (e.g. Zephyr MPU).
 */
#define OVE_THREAD_STACK_MEMBER_(name, size) uint8_t __attribute__((aligned(8))) name[size]
#endif

