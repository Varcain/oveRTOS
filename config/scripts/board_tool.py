def _write_file(path, content, force=False):
    """Write content — force overwrites entirely, default uses marker-based merge."""
    if force:
        dirname = os.path.dirname(path)
        if dirname:
            os.makedirs(dirname, exist_ok=True)
        with open(path, "w") as f:
            f.write(content)
        return
    _write_with_markers(path, content)


def _write_with_markers(path, content):
    """Write content with auto-generation markers.

    If file exists and has markers, replace only the marked region.
    If file exists without markers, prepend content.
    If file does not exist, create it.
    """
    # Detect which marker style is used in the content
    if AUTO_BEGIN_C in content:
        begin_marker = AUTO_BEGIN_C
        end_marker = AUTO_END_C
    else:
        begin_marker = AUTO_BEGIN
        end_marker = AUTO_END

    if os.path.isfile(path):
        with open(path, "r") as f:
            existing = f.read()
        begin_idx = existing.find(begin_marker)
        end_idx = existing.find(end_marker, begin_idx) if begin_idx >= 0 else -1
        if begin_idx >= 0 and end_idx >= 0:
            # Replace between markers
            before = existing[:begin_idx]
            after = existing[end_idx + len(end_marker):]
            merged = before + content + after
            with open(path, "w") as f:
                f.write(merged)
            return
        # File exists but no markers — prepend
        with open(path, "w") as f:
            f.write(content + "\n" + existing)
        return

    dirname = os.path.dirname(path)
    if dirname:
        os.makedirs(dirname, exist_ok=True)
    with open(path, "w") as f:
        f.write(content)


