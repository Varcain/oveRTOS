def _register_kconfig(ove_name, board_yaml_data):
    """Auto-register a board in Config.in.hardware (idempotent)."""
    kconfig_path = os.path.join(ove_dir(), "config", "Config.in.hardware")
    if not os.path.isfile(kconfig_path):
        print(f"  Warning: {kconfig_path} not found, skipping Kconfig registration")
        return

    board = board_yaml_data.get("board", {})
    memory = board_yaml_data.get("memory", {})
    clock = board_yaml_data.get("clock", {})

    # Derive Kconfig symbol: OVE_BOARD_ + name uppercased with - → _
    symbol = "OVE_BOARD_" + ove_name.upper().replace("-", "_")

    with open(kconfig_path, "r") as f:
        lines = f.readlines()

    # Check if symbol already exists or board name already mapped
    for line in lines:
        if line.strip().startswith(f"config {symbol}"):
            print(f"  Kconfig: {symbol} already registered, skipping")
            return
        if f'default "{ove_name}"' in line:
            print(f"  Kconfig: {ove_name} already mapped in defaults, skipping")
            return

    mcu_family = board.get("mcu_family", "unknown")
    mcu = board.get("mcu", "unknown")
    flash_kb = memory.get("flash_kb", 0)
    ram_kb = memory.get("ram_kb", 0)
    sysclk = clock.get("sysclk_mhz", "")

    flash_bytes = flash_kb * 1024
    ram_bytes = ram_kb * 1024

    # Build the choice entry block (two-line help matching existing style)
    pretty_name = ove_name.upper()
    help_line1 = f"{pretty_name} board ({mcu_family.upper()} family)."
    spec_parts = []
    if sysclk:
        spec_parts.append(f"@ {sysclk} MHz")
    if flash_kb:
        if flash_kb >= 1024:
            spec_parts.append(f"{flash_kb // 1024} MB Flash")
        else:
            spec_parts.append(f"{flash_kb} KB Flash")
    if ram_kb:
        if ram_kb >= 1024:
            spec_parts.append(f"{ram_kb // 1024} MB RAM")
        else:
            spec_parts.append(f"{ram_kb} KB RAM")
    help_line2 = f"MCU {mcu}" + (", " + ", ".join(spec_parts) if spec_parts else "") + "."

    choice_entry = (
        f"\nconfig {symbol}\n"
        f'    bool "{pretty_name}"\n'
        f"    help\n"
        f"      {help_line1}\n"
        f"      {help_line2}\n"
    )

    # Insert choice entry before 'endchoice'
    # Insert defaults after last default in each section
    new_lines = []
    in_section = None  # track which config section we're in
    for i, line in enumerate(lines):
        stripped = line.rstrip()

        # Insert choice block before endchoice
        if stripped == "endchoice":
            new_lines.append(choice_entry)
            new_lines.append(line)
            continue

        # Track which config section we're in
        if stripped.startswith("config OVE_BOARD_NAME"):
            in_section = "BOARD_NAME"
        elif stripped.startswith("config OVE_FLASH_SIZE"):
            in_section = "FLASH_SIZE"
        elif stripped.startswith("config OVE_RAM_SIZE"):
            in_section = "RAM_SIZE"
        elif stripped.startswith("config OVE_MCU"):
            in_section = "MCU"
        elif stripped.startswith("config ") or stripped.startswith("endmenu"):
            in_section = None

        new_lines.append(line)

        # After the last 'default ...' in each section, insert our default
        if in_section and stripped.strip().startswith("default "):
            # Peek ahead: if the next non-empty line is NOT a default, insert ours
            next_is_default = False
            for j in range(i + 1, len(lines)):
                next_stripped = lines[j].strip()
                if not next_stripped:
                    continue
                if next_stripped.startswith("default "):
                    next_is_default = True
                break
            if not next_is_default:
                if in_section == "BOARD_NAME":
                    new_lines.append(
                        f'    default "{ove_name}" if {symbol}\n'
                    )
                elif in_section == "FLASH_SIZE":
                    new_lines.append(
                        f"    default {flash_bytes} if {symbol}\n"
                    )
                elif in_section == "RAM_SIZE":
                    new_lines.append(
                        f"    default {ram_bytes} if {symbol}\n"
                    )
                elif in_section == "MCU":
                    new_lines.append(
                        f'    default "{mcu}" if {symbol}\n'
                    )

    with open(kconfig_path, "w") as f:
        f.writelines(new_lines)
    print(f"  Kconfig: registered {symbol}")


def _register_constants(ove_name, board_yaml_data, rtos):
    """Auto-register RTOS board mapping in constants.py (idempotent)."""
    constants_path = os.path.join(
        ove_dir(), "config", "ove-cli", "ove", "constants.py"
    )
    if not os.path.isfile(constants_path):
        print(f"  Warning: {constants_path} not found, skipping constants registration")
        return

    meta = board_yaml_data.get("_meta", {})

    with open(constants_path, "r") as f:
        content = f.read()

    if rtos == "nuttx":
        nuttx_board = meta.get("nuttx_board", "")
        nuttx_config = meta.get("nuttx_config", "nsh")
        if not nuttx_board:
            print("  Constants: no nuttx_board in _meta, skipping NuttX mapping")
            return
        entry = f'    "{ove_name}": "{nuttx_board}:{nuttx_config}",'
        dict_name = "NUTTX_BOARD_CONFIGS"
    elif rtos == "zephyr":
        zephyr_board = meta.get("zephyr_board", "")
        if not zephyr_board:
            print("  Constants: no zephyr_board in _meta, skipping Zephyr mapping")
            return
        entry = f'    "{ove_name}": "{zephyr_board}",'
        dict_name = "ZEPHYR_BOARD_MAPPINGS"
    else:
        return

    # Check if already present
    if f'"{ove_name}"' in content and dict_name in content:
        # More precise check: is it in the right dict?
        in_dict = False
        for line in content.splitlines():
            if dict_name in line:
                in_dict = True
            if in_dict and f'"{ove_name}"' in line:
                print(f"  Constants: {ove_name} already in {dict_name}, skipping")
                return
            if in_dict and line.strip() == "}":
                in_dict = False

    # Find closing } of the target dict and insert before it
    lines = content.splitlines(True)
    new_lines = []
    in_target_dict = False
    inserted = False
    for line in lines:
        if dict_name in line and "=" in line:
            in_target_dict = True
        if in_target_dict and not inserted and line.strip() == "}":
            new_lines.append(entry + "\n")
            inserted = True
            in_target_dict = False
        new_lines.append(line)

    if inserted:
        with open(constants_path, "w") as f:
            f.writelines(new_lines)
        print(f"  Constants: registered {ove_name} in {dict_name}")
    else:
        print(f"  Warning: could not find {dict_name} closing brace in constants.py")


def _generate_defconfig(ove_name, board_yaml_data, rtos):
    """Auto-generate a minimal example defconfig for the board."""
    board = board_yaml_data.get("board", {})
    mcu = board.get("mcu", "")

    # Derive short name: STM32F429xx → stm32f429, NRF52840 → nrf52840
    short = mcu.lower().rstrip("x") if mcu else ove_name.split("-")[0]

    defconfig_dir = os.path.join(ove_dir(), "defconfigs", short)
    defconfig_name = f"{short}_{rtos}_example_c_defconfig"
    defconfig_path = os.path.join(defconfig_dir, defconfig_name)

    if os.path.isfile(defconfig_path):
        print(f"  Defconfig: {defconfig_name} already exists, skipping")
        return

    # Kconfig symbol for the board
    symbol = "OVE_BOARD_" + ove_name.upper().replace("-", "_")

    lines = [
        "CONFIG_OVE_APP_EXAMPLE_C=y",
        "CONFIG_OVE_APP_LANG_C=y",
        f"CONFIG_OVE_RTOS_{rtos.upper()}=y",
        f"CONFIG_{symbol}=y",
        "CONFIG_OVE_SYNC=y",
        "# CONFIG_OVE_AUDIO is not set",
        "# CONFIG_OVE_FS is not set",
        "CONFIG_OVE_CONSOLE=y",
        "CONFIG_OVE_LOG=y",
        "CONFIG_OVE_TIME=y",
        "CONFIG_OVE_BSP=y",
        "# CONFIG_OVE_LVGL is not set",
        "CONFIG_OVE_QUEUE=y",
        "CONFIG_OVE_TIMER=y",
        "CONFIG_OVE_EVENTGROUP=y",
        "# CONFIG_OVE_SHELL is not set",
        "# CONFIG_OVE_NVS is not set",
        "# CONFIG_OVE_WATCHDOG is not set",
        "# CONFIG_OVE_WORKQUEUE is not set",
        "# CONFIG_OVE_STREAM is not set",
        "CONFIG_OVE_LOG_LEVEL_INF=y",
    ]

    if rtos == "nuttx":
        lines.append("CONFIG_NUTTX_SOURCE_GIT=y")

    if rtos == "zephyr":
        # Disable Zephyr subsystems not supported by this board
        if "sdcard" not in board_yaml_data:
            lines.append("# CONFIG_ZEPHYR_SD_FILESYSTEM is not set")

    lines.append("CONFIG_OVE_TOOLCHAIN_DOWNLOAD=y")

    os.makedirs(defconfig_dir, exist_ok=True)
    with open(defconfig_path, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"  Defconfig: created {os.path.relpath(defconfig_path, ove_dir())}")


def _generate_flash_scripts(board_dir, rtos, mcu_family, ove_name,
                            mcu=""):
    """Auto-generate flash.sh, debug.sh, and gdb.sh for the board."""
    rtos_dir = os.path.join(board_dir, rtos)
    if not os.path.isdir(rtos_dir):
        return

    # Discover OpenOCD board config
    openocd_scripts = "/usr/share/openocd/scripts/board"
    openocd_cfg = None

    # Derive chip prefix for precise matching: STM32F429xx → stm32f429
    chip_prefix = mcu.lower().rstrip("x") if mcu else ""

    if os.path.isdir(openocd_scripts):
        board_files = sorted(os.listdir(openocd_scripts))

        # Strategy 1: match by chip prefix (most specific)
        if chip_prefix:
            for f in board_files:
                if chip_prefix in f and f.endswith(".cfg"):
                    openocd_cfg = f"board/{f}"
                    break

        # Strategy 2: match by mcu_family + "discovery"
        if not openocd_cfg:
            candidate = f"{mcu_family}discovery.cfg"
            if os.path.isfile(os.path.join(openocd_scripts, candidate)):
                openocd_cfg = f"board/{candidate}"

    # Strategy 3: fallback
    if not openocd_cfg:
        openocd_cfg = f"board/{mcu_family}discovery.cfg"

    pretty_name = ove_name.upper()

    scripts = {
        "flash.sh": (
            f"#!/bin/bash\n"
            f"# Flash script for {pretty_name} ({rtos.capitalize()})\n"
            f"# Usage: flash.sh <firmware.elf>\n"
            f"\n"
            f"set -e\n"
            f"\n"
            f'FIRMWARE="${{1:?Usage: $0 <firmware.elf>}}"\n'
            f"\n"
            f'if [ ! -f "$FIRMWARE" ]; then\n'
            f'    echo "Error: firmware file not found: $FIRMWARE"\n'
            f"    exit 1\n"
            f"fi\n"
            f"\n"
            f"openocd \\\n"
            f"    -f {openocd_cfg} \\\n"
            f'    -c "program $FIRMWARE verify reset exit"\n'
        ),
        "debug.sh": (
            f"#!/bin/bash\n"
            f"# Start OpenOCD debug server for {pretty_name} ({rtos.capitalize()})\n"
            f"# Usage: debug.sh\n"
            f"\n"
            f"set -e\n"
            f"\n"
            f"openocd -f {openocd_cfg}\n"
        ),
        "gdb.sh": (
            f"#!/bin/bash\n"
            f"# Connect GDB to OpenOCD for {pretty_name} ({rtos.capitalize()})\n"
            f"# Usage: gdb.sh <firmware.elf>\n"
            f"\n"
            f"set -e\n"
            f"\n"
            f'FIRMWARE="${{1:?Usage: $0 <firmware.elf>}}"\n'
            f"\n"
            f'if [ ! -f "$FIRMWARE" ]; then\n'
            f'    echo "Error: firmware file not found: $FIRMWARE"\n'
            f"    exit 1\n"
            f"fi\n"
            f"\n"
            f'arm-none-eabi-gdb "$FIRMWARE" \\\n'
            f'    -ex "target extended-remote :3333" \\\n'
            f'    -ex "monitor reset halt" \\\n'
            f'    -ex "load"\n'
        ),
    }

    for name, content in scripts.items():
        script_path = os.path.join(rtos_dir, name)
        if os.path.isfile(script_path):
            print(f"  Scripts: {name} already exists, skipping")
            continue
        with open(script_path, "w") as f:
            f.write(content)
        os.chmod(script_path, 0o755)
        print(f"  Scripts: created {os.path.relpath(script_path, ove_dir())}")


def _post_import_register(ove_name, board_yaml_data, rtos):
    """Run all post-import registration hooks."""
    print(f"\n--- Post-import registration for {ove_name} ({rtos}) ---")
    _register_kconfig(ove_name, board_yaml_data)
    _register_constants(ove_name, board_yaml_data, rtos)
    _generate_defconfig(ove_name, board_yaml_data, rtos)
    board_dir = os.path.join(boards_dir(), ove_name)
    board = board_yaml_data.get("board", {})
    mcu_family = board.get("mcu_family", "unknown")
    mcu = board.get("mcu", "")
    _generate_flash_scripts(board_dir, rtos, mcu_family, ove_name, mcu=mcu)
    print("--- Registration complete ---\n")


