def _import_zephyr(args):
    zephyr_base = args.zephyr_base or os.path.join(dl_dir(), "zephyr-workspace", "zephyr")
    board_name = args.board

    if not os.path.isdir(zephyr_base):
        print(f"Error: Zephyr base not found: {zephyr_base}")
        print("  Download Zephyr first or specify --zephyr-base")
        sys.exit(1)

    board_dir = _find_zephyr_board_dir(zephyr_base, board_name)
    if not board_dir:
        print(f"Error: Zephyr board '{board_name}' not found in {zephyr_base}/boards/")
        sys.exit(1)

    print(f"Importing Zephyr board: {board_name}")
    print(f"  Source: {board_dir}")

    # Parse DTS
    dts_text = _read_dts_files(board_dir, board_name)
    if not dts_text:
        print(f"  Warning: no DTS files found in {board_dir}")
        data = {"board": {"name": board_name.replace("_", "-"), "mcu_family": "unknown", "mcu": "unknown"}}
        warnings = ["No DTS files found — board.yaml will be minimal"]
    else:
        tree = DtsParser(dts_text).parse()
        data, warnings = _extract_board_yaml_from_dts(tree, board_name)

    # oveRTOS board name
    ove_name = args.ove_name or data["board"]["name"]
    data["board"]["name"] = ove_name

    # Add provenance
    data["_meta"] = {
        "imported_from": "zephyr",
        "import_date": datetime.date.today().isoformat(),
        "zephyr_board": board_name,
    }

    # Target directory
    target_dir = os.path.join(boards_dir(), ove_name)

    # Check for existing board.yaml
    yaml_path = os.path.join(target_dir, "board.yaml")
    if os.path.isfile(yaml_path):
        board_yaml = _resolve_conflict(yaml_path, data, args)
        if board_yaml is None:
            return
    else:
        board_yaml = BoardYaml(data=data)

    # Validate (strip _meta)
    board_yaml.validate()

    # Save board.yaml
    os.makedirs(target_dir, exist_ok=True)
    board_yaml.save(yaml_path)
    print(f"  Saved: {os.path.relpath(yaml_path, ove_dir())}")

    # Create Zephyr scaffold
    zephyr_board_name = board_name  # keep original Zephyr name for .conf/.overlay
    zephyr_scaffold_dir = os.path.join(target_dir, "zephyr")
    _render_scaffold(
        "zephyr",
        ove_name,
        data["board"]["mcu_family"],
        data["board"]["mcu"],
        zephyr_scaffold_dir,
    )

    # Create boards/ subdirectory with empty .conf and .overlay
    zephyr_boards_dir = os.path.join(zephyr_scaffold_dir, "boards")
    os.makedirs(zephyr_boards_dir, exist_ok=True)
    for ext in [".conf", ".overlay"]:
        fpath = os.path.join(zephyr_boards_dir, f"{zephyr_board_name}{ext}")
        if not os.path.isfile(fpath):
            with open(fpath, "w") as f:
                if ext == ".conf":
                    f.write(f"{AUTO_BEGIN}\n{AUTO_END}\n")
                else:
                    f.write(f"{AUTO_BEGIN_C}\n{AUTO_END_C}\n")
            print(f"  Created: {os.path.relpath(fpath, ove_dir())}")

    # Post-import registration — use saved board.yaml data (may differ from
    # extracted data if user kept existing), but merge in new _meta so RTOS
    # mapping info (zephyr_board) is available for constants registration.
    reg_data = board_yaml.data
    reg_data.setdefault("_meta", {}).update(data.get("_meta", {}))
    _post_import_register(ove_name, reg_data, "zephyr")

    # Print warnings
    if warnings:
        print("\n  Fields that need manual review:")
        for w in warnings:
            print(f"    - {w}")

    print(f"\nImport complete: boards/{ove_name}/")


