def _sync_zephyr(board_yaml, board_dir, force=False):
    """Generate Zephyr .conf and .overlay from board.yaml."""
    data = board_yaml.data
    board_name = data["board"]["name"]
    # Prefer the original Zephyr board name from import metadata, then
    # check for existing .conf files in the boards/ subdirectory, and
    # finally fall back to deriving from the ove board name.
    meta = data.get("_meta", {})
    zephyr_name = meta.get("zephyr_board", None)
    if not zephyr_name:
        # Check for existing .conf files to discover the Zephyr name
        boards_subdir_check = os.path.join(board_dir, "zephyr", "boards")
        if os.path.isdir(boards_subdir_check):
            for f in os.listdir(boards_subdir_check):
                if f.endswith(".conf") and not f.startswith("."):
                    zephyr_name = f[: -len(".conf")]
                    break
    if not zephyr_name:
        zephyr_name = board_name.replace("-", "_")

    zephyr_dir = os.path.join(board_dir, "zephyr")
    if not os.path.isdir(zephyr_dir):
        print(f"  Skipping Zephyr sync: {zephyr_dir} does not exist")
        return

    boards_subdir = os.path.join(zephyr_dir, "boards")
    os.makedirs(boards_subdir, exist_ok=True)

    # --- .conf ---
    conf_path = os.path.join(boards_subdir, f"{zephyr_name}.conf")
    conf_lines = [AUTO_BEGIN]

    if "audio" in data:
        if "i2s" in data["audio"]:
            conf_lines.append("CONFIG_I2S=y")
            conf_lines.append("CONFIG_I2C=y")
            conf_lines.append("CONFIG_DMA=y")
            conf_lines.append("CONFIG_AUDIO=y")
        if "codec" in data["audio"]:
            conf_lines.append("CONFIG_AUDIO_CODEC=y")

    if "sdcard" in data:
        conf_lines.append("CONFIG_DISK_ACCESS=y")
        conf_lines.append("CONFIG_DISK_DRIVERS=y")
        conf_lines.append("CONFIG_DISK_DRIVER_SDMMC=y")

    if "display" in data:
        conf_lines.append("CONFIG_DISPLAY=y")

    ram_kb = data.get("memory", {}).get("ram_kb", 0)
    if ram_kb > 256:
        heap_size = min(ram_kb * 64, 262144)  # scale, cap at 256K
        conf_lines.append(f"CONFIG_HEAP_MEM_POOL_SIZE={heap_size}")

    conf_lines.append(AUTO_END)
    _write_file(conf_path, "\n".join(conf_lines) + "\n", force=force)
    print(f"  Synced: {os.path.relpath(conf_path, ove_dir())}")

    # --- .overlay ---
    overlay_path = os.path.join(boards_subdir, f"{zephyr_name}.overlay")
    overlay_lines = [AUTO_BEGIN_C]

    # LEDs overlay
    if "leds" in data and data["leds"]:
        overlay_lines.append("")
        overlay_lines.append("/ {")
        overlay_lines.append("\tleds {")
        overlay_lines.append('\t\tcompatible = "gpio-leds";')
        for i, led in enumerate(data["leds"]):
            port_letter = chr(ord("a") + led.get("port", 0))
            pin = led.get("pin", 0)
            flags = "GPIO_ACTIVE_LOW" if led.get("active_low") else "GPIO_ACTIVE_HIGH"
            overlay_lines.append(f"\t\tled_{i}: led_{i} {{")
            overlay_lines.append(f"\t\t\tgpios = <&gpio{port_letter} {pin} {flags}>;")
            overlay_lines.append(f"\t\t}};")
        overlay_lines.append("\t};")
        overlay_lines.append("};")

    # Serial console
    serial = data.get("serial", {}).get("console", {})
    baud = serial.get("baud")
    if baud:
        overlay_lines.append("")
        overlay_lines.append("/* TODO: verify USART instance — defaulting to usart1 */")
        overlay_lines.append(f"&usart1 {{")
        overlay_lines.append(f"\tcurrent-speed = <{baud}>;")
        overlay_lines.append(f'\tstatus = "okay";')
        overlay_lines.append(f"}};")

    # Audio codec
    codec = data.get("audio", {}).get("codec", {})
    if codec:
        addr_str = codec.get("i2c_addr", "0x1A")
        addr_int = int(addr_str, 16) if isinstance(addr_str, str) else addr_str
        codec_type = codec.get("type", "unknown")
        # Try to form a compatible string
        compat_str = codec_type.lower()
        if compat_str.startswith("wm"):
            compat_str = f"wolfson,{compat_str.lower()}"
        elif compat_str.startswith("cs"):
            compat_str = f"cirrus,{compat_str.lower()}"

        overlay_lines.append("")
        overlay_lines.append("/* TODO: verify I2C instance — defaulting to i2c3 */")
        overlay_lines.append(f"&i2c3 {{")
        overlay_lines.append(f"audio_codec: {compat_str.split(',')[-1]}@{addr_int:x} {{")
        overlay_lines.append(f'\tcompatible = "{compat_str}";')
        overlay_lines.append(f"\treg = <0x{addr_int:02x}>;")
        overlay_lines.append(f"\t#sound-dai-cells = <0>;")
        overlay_lines.append(f'\tstatus = "okay";')
        overlay_lines.append(f"}};")
        overlay_lines.append(f"}};")

    # Display
    display = data.get("display", {})
    if display.get("width") and display.get("height"):
        overlay_lines.append("")
        overlay_lines.append(f"/* Display: {display['width']}x{display['height']} */")
        overlay_lines.append(f"/* TODO: Add display panel node with appropriate compatible */")

    # Audio I2S scaffold
    if data.get("audio", {}).get("i2s"):
        overlay_lines.append("")
        overlay_lines.append("/* TODO: SAI/I2S peripheral config */")

    overlay_lines.append("")
    overlay_lines.append(AUTO_END_C)
    _write_file(overlay_path, "\n".join(overlay_lines) + "\n", force=force)
    print(f"  Synced: {os.path.relpath(overlay_path, ove_dir())}")


