"""Configuration generation package.

Split out of the original ``configure.py`` for navigability:

- :mod:`templates`   — Jinja2 rendering of ove_config.h / .cmake / RTOS configs
- :mod:`board_desc`  — board.yaml -> board_desc.h
- :mod:`assets`      — app.yaml + image pipeline -> app_sources.cmake
- :mod:`patches`     — RTOS source patching (legacy; build.py has its own)
"""

import json
import os

from .templates import render_template, generate_configs
from .board_desc import generate_board_desc
from .assets import generate_app_sources
from .patches import apply_patches, apply_all_patches

# Records the .config that generated/ was rendered from; read back by
# ove build to refuse a stale configuration.
CONFIG_SENTINEL = ".config_generated_sha256"

__all__ = [
    "render_template",
    "generate_configs",
    "generate_board_desc",
    "generate_app_sources",
    "apply_patches",
    "apply_all_patches",
    "configure_all",
    "cmd_configure",
]


def configure_all(ws):
    """Run full configuration: board desc + app sources + template generation."""
    ws.require_config()
    ws.ensure_dirs()
    generate_board_desc(ws)
    generate_app_sources(ws)
    print("=== Generating configuration ===")
    generate_configs(ws)
    _emit_cmake_user_presets(ws)
    _record_generated_config(ws)


def _record_generated_config(ws):
    """Stamp which .config the files in generated/ were rendered from.

    Nothing re-runs configure automatically, and a generated header left over
    from a previous configuration is still perfectly valid C — so a build after
    a .config change silently compiles the old configuration. 'ove build'
    compares this stamp to catch that.

    Hash rather than mtime: .config is a symlink that defconfig repoints
    between workspaces, so its timestamp does not advance monotonically and an
    older-but-different config would compare as current.
    """
    from ..utils import hash_file

    path = os.path.join(ws.workspace_dir, CONFIG_SENTINEL)
    with open(path, "w") as f:
        f.write(hash_file(ws.config_path) + "\n")


def _emit_cmake_user_presets(ws):
    """Write a CMakeUserPresets.json at repo root for IDE consumption.

    The preset points at whichever workspace was just configured. IDEs
    (VS Code CMake Tools, CLion) pick this up automatically and can
    configure / build without going through `make` or `ove build`.
    """
    if ws.rtos == "nuttx":
        # NuttX wraps cmake itself; an external preset would just confuse
        # CLion when it tries to invoke without nuttx-cmake's build glue.
        return
    board_dir = ws.board_dir
    if not board_dir:
        return

    binary_dir = os.path.join(ws.build_dir, "firmware")
    cache_vars = {
        "OVE_DIR": ws.ove_dir,
        "OVE_GEN_DIR": ws.gen_dir,
        "OVE_DL_DIR": ws.ws_dl_dir,
        "BOARD_DIR": board_dir,
    }
    if ws.app_dir:
        cache_vars["OVE_APP_DIR"] = ws.app_dir
    if ws.toolchain_dir:
        cache_vars["OVE_TOOLCHAIN_DIR"] = ws.toolchain_dir
    if ws.rtos == "freertos":
        # The compiler ABI is consumed by CMake's toolchain file before
        # project() and before generated ove_config.cmake can be included.
        cache_vars["OVE_ARM_FLOAT_ABI"] = ws.arm_float_abi
    toolchain_file = os.path.join(board_dir, "cmake", "arm-none-eabi.cmake")
    if os.path.isfile(toolchain_file):
        cache_vars["CMAKE_TOOLCHAIN_FILE"] = toolchain_file

    preset_name = (
        f"ove-{ws.board_name or 'unknown'}-{ws.rtos or 'unknown'}"
        f"-{os.path.basename(ws.app_dir) if ws.app_dir else 'noapp'}"
    )
    presets = {
        "version": 6,
        "cmakeMinimumRequired": {
            "major": 3, "minor": 25, "patch": 0,
        },
        "configurePresets": [{
            "name": preset_name,
            "displayName": f"oveRTOS - {preset_name}",
            "description": (
                "Generated by `ove configure`. Re-run after switching "
                "workspace; this file is gitignored."),
            "binaryDir": binary_dir,
            "generator": "Unix Makefiles",
            "cacheVariables": cache_vars,
        }],
        "buildPresets": [{
            "name": preset_name,
            "configurePreset": preset_name,
        }],
    }
    out = os.path.join(ws.ove_dir, "CMakeUserPresets.json")
    with open(out, "w") as f:
        json.dump(presets, f, indent=2)
        f.write("\n")
    print(f"  Generated: {out}")


def cmd_configure(args):
    """CLI entry point for 'ove configure'."""
    import os
    from ..workspace import Workspace
    ws = Workspace()
    if getattr(args, "dry_run", False):
        ws.require_config()
        print(f"[dry-run] would generate config for {ws.rtos}")
        print(f"[dry-run] gen dir:    {ws.gen_dir}")
        targets = ["ove_config.h", "ove_config.cmake"]
        if ws.rtos == "freertos":
            targets.append("FreeRTOSConfig.h")
        elif ws.rtos == "zephyr":
            targets.append("prj.conf")
        elif ws.rtos == "nuttx":
            targets.append("nuttx_defconfig")
        for t in targets:
            print(f"[dry-run]   -> {os.path.join(ws.gen_dir, t)}")
        if ws.app_dir:
            print(f"[dry-run]   -> {os.path.join(ws.gen_dir, 'app_sources.cmake')}")
        if ws.board_dir:
            print(f"[dry-run]   -> {os.path.join(ws.gen_dir, 'board_desc.h')}")
        return
    configure_all(ws)
